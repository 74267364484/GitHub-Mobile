export type IconName = keyof typeof ICONS

export function Octicon({
  name, size = 16, className, title,
}: {
  name: IconName
  size?: number
  className?: string
  title?: string
}) {
  const C = ICONS[name] || O.DotFillIcon
  return <C size={size} className={className} aria-label={title} aria-hidden={title ? undefined : true} />
}
